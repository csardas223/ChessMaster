#!/usr/bin/env node
/* Regenerates the classic-script data files the app loads synchronously (so it also runs from file://):
     data/videos.json        -> data/videos.js         (window.CM_DATA.videos)
     data/legacy_modes.json  -> data/legacy_modes.js   (window.CM_DATA.legacyModes)
     data/modes/<id>.js      -> data/modes/index.js    (window.CM_DATA.modeIndex: id -> {title, name, category, frame})
     js/legacy/* + the above -> data/legacy_index.js   (window.CM_DATA.legacyNames: id -> legacy mode name, pol-perf)
     all of the above        -> data/kinds.js          (window.CM_DATA.videoKinds: id -> short category badge, pol-ui)
   Mode files are loaded on demand by the app; the index only tells the lobby which videos are remastered.
   Each mode file is evaluated in a sandbox with a stub CM.mode() to validate it.
   Usage: node tools/build-data.mjs [--check]   (--check exits non-zero on errors) */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { modeKind } from './mode-kind.mjs';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = path.join(root, 'data');
const check = process.argv.includes('--check');
let errors = 0, warnings = 0;
const err = (m) => { console.error('ERROR ' + m); errors++; };
const warn = (m) => { console.warn('warn  ' + m); warnings++; };

function wrap(name, key, obj) {
  return `/* generated by tools/build-data.mjs from data/${name}; do not edit by hand */\n` +
    `window.CM_DATA=window.CM_DATA||{};window.CM_DATA.${key}=${JSON.stringify(obj)};\n`;
}
const videos = JSON.parse(fs.readFileSync(path.join(data, 'videos.json'), 'utf8'));
const ids = new Set(videos.map(v => v.id));
fs.writeFileSync(path.join(data, 'videos.js'), wrap('videos.json', 'videos', videos));
const legacy = JSON.parse(fs.readFileSync(path.join(data, 'legacy_modes.json'), 'utf8'));
fs.writeFileSync(path.join(data, 'legacy_modes.js'), wrap('legacy_modes.json', 'legacyModes', legacy));

/* pol-perf: the legacy library (js/legacy/*, ~300 KB) is lazy-loaded when a legacy video opens; the lobby only needs
   each video's legacy mode name (and whether one exists, for Random). Compute them here by running the legacy scripts
   in a DOM-less sandbox exactly the way lobby.js used to at boot (fill VIDEOS, then modeFor/modeName per video). */
const legacyNames = {};
try {
  const lsb = { console: { log() { }, warn() { }, error() { } }, CM: { settings: { pieceUrl: () => '' } },
    document: { readyState: 'loading', addEventListener() { } } /* no createElement: modes_extra.js skips its DOM setup */, __vids: videos.map(v => [v.id, v.title, v.category]) };
  lsb.window = lsb; lsb.CM_DATA = { legacyModes: legacy }; vm.createContext(lsb);
  const lsrc = ['engine8', 'glue', 'modes_extra'].map(f => fs.readFileSync(path.join(root, 'js', 'legacy', f + '.js'), 'utf8')).join('\n;\n');
  vm.runInContext(lsrc + `
;__vids.forEach(function (a) { a.explain = null; VIDEOS.push(a); });
globalThis.__out = {}; VIDEOS.forEach(function (a) { try { a.mode = modeFor(a[1], a[2]); __out[a[0]] = modeName(a.mode.m, a.mode.arg); } catch (e) { } });`, lsb, { filename: 'legacy-index', timeout: 10000 });
  Object.assign(legacyNames, lsb.__out);
} catch (e) { err(`legacy index: ${e.message}`); }
fs.writeFileSync(path.join(data, 'legacy_index.js'), `/* generated by tools/build-data.mjs from js/legacy/*.js + data/videos.json + data/legacy_modes.json; do not edit by hand */\nwindow.CM_DATA=window.CM_DATA||{};window.CM_DATA.legacyNames=${JSON.stringify(legacyNames)};\n`);

const KNOWN = new Set(['id', 'title', 'name', 'category', 'description', 'how_to_win', 'player_side', 'opponent', 'player', 'board', 'pieces', 'setup',
  'rules', 'bot', 'clock', 'events', 'vfx', 'vfx_timeline', 'hooks', 'params', 'assets', 'sounds', 'engine', 'legacy', 'official_site_url',
  'source', 'notes', 'version', 'confidence', 'intro', 'messages', 'ui', 'players', 'frame', 'game', 'theme', 'thumb', 'subtitle',
  'video', 'research', 'levels', 'intro_message', 'no_video', 'tags', 'lobby', 'status', 'todo_pass2' /* two-pass plan: what pass 2 still has to add */]);

/* keep the badges already in data/kinds.js: run after run the generated file must not churn */
const prevKinds = (() => {
  try {
    const sb = { window: {} };
    vm.runInNewContext(fs.readFileSync(path.join(data, 'kinds.js'), 'utf8'), sb);
    return (sb.window.CM_DATA || {}).videoKinds || {};
  } catch (e) { return {}; }
})();
const dir = path.join(data, 'modes');
const index = {};
const modeFacts = {};
for (const f of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  if (!f.endsWith('.js') || f === 'index.js') continue;
  const id = f.replace(/\.js$/, '');
  const got = [];
  const sandbox = { window: {}, console, CM: { mode: (s) => { got.push(s); return s; }, defineHooks: () => { }, util: {} } };
  sandbox.window.CM = sandbox.CM;
  try { vm.runInNewContext(fs.readFileSync(path.join(dir, f), 'utf8'), sandbox, { filename: f, timeout: 2000 }); }
  catch (e) { err(`${f}: ${e.message}`); continue; }
  if (got.length !== 1) { err(`${f}: must call CM.mode({...}) exactly once (called ${got.length} times)`); continue; }
  const s = got[0];
  if (s.id !== id) err(`${f}: id "${s.id}" does not match the file name`);
  for (const k of Object.keys(s)) if (!KNOWN.has(k) && k[0] !== '_') warn(`${f}: unknown top-level key "${k}"`);
  if (!ids.has(id) && !s.no_video) warn(`${f}: no video with this id in data/videos.json (set no_video: true for app-only modes)`);
  if (s.frame === 'game') {
    const m = s.game && s.game.module;
    if (!m) err(`${f}: frame "game" needs game.module`);
    else if (!fs.existsSync(path.join(root, 'js', 'games', m + '.js'))) err(`${f}: js/games/${m}.js not found`);
  }
  if (typeof s.hooks === 'string' && !fs.existsSync(path.join(root, 'js', 'modes', s.hooks.replace(/^js\/modes\//, '').replace(/\.js$/, '') + '.js'))) err(`${f}: hooks module js/modes/${s.hooks}.js not found`);
  const b = s.board || {};
  if ((b.files || 8) > 32 || (b.ranks || 8) > 32) err(`${f}: board larger than 32x32`);
  index[id] = { title: s.title || null, name: s.name || s.title || id, category: s.category || null, frame: s.frame || 'chess' };
  modeFacts[id] = { title: s.title, name: s.name, category: s.category, frame: s.frame, players: Array.isArray(s.players) ? s.players.length : 0,
    hooks: typeof s.hooks === 'string' ? s.hooks.replace(/^js\/modes\//, '').replace(/\.js$/, '') : (s.hooks && typeof s.hooks.extends === 'string' ? s.hooks.extends : '') };
}
/* pol-ui: short category badge per video (tools/mode-kind.mjs), for mode files and legacy-only videos alike */
const videoKinds = {};
for (const v of videos) {
  const f = modeFacts[v.id] || {};
  videoKinds[v.id] = modeKind({ title: v.title || f.title, name: f.name || legacyNames[v.id] || '', category: v.category || f.category, frame: f.frame, players: f.players, hooks: f.hooks }, prevKinds[v.id]);
}
for (const id of Object.keys(modeFacts)) if (!videoKinds[id]) videoKinds[id] = modeKind(modeFacts[id], prevKinds[id]);
fs.writeFileSync(path.join(dir, 'index.js'), `/* generated by tools/build-data.mjs from data/modes/*.js; do not edit by hand */\nwindow.CM_DATA=window.CM_DATA||{};window.CM_DATA.modeIndex=${JSON.stringify(index)};\n`);
/* own file: tools (qa_all.py, bot_engine_probe.py) parse data/modes/index.js as a single modeIndex assignment */
fs.writeFileSync(path.join(data, 'kinds.js'), `/* generated by tools/build-data.mjs (tools/mode-kind.mjs); do not edit by hand */\nwindow.CM_DATA=window.CM_DATA||{};window.CM_DATA.videoKinds=${JSON.stringify(videoKinds)};\n`);
console.log(`videos: ${videos.length}, legacy configs: ${Object.keys(legacy).length}, legacy names: ${Object.keys(legacyNames).length}, mode files indexed: ${Object.keys(index).length}` + (warnings ? `, warnings: ${warnings}` : '') + (errors ? `, ERRORS: ${errors}` : ''));
if (check && errors) process.exit(1);
