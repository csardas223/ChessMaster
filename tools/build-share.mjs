/* m-og: short links + link previews for every mode. Called by tools/build-data.mjs (also runs on its own).
   - data/slugs.json   id -> slug registry. Slugs are STABLE: an id keeps the slug it was first given, even if the mode
                       is renamed; only new modes get new slugs. A slug is the mode's name in lowercase-hyphen form; on a
                       clash the video title is tried, then -2, -3 ... Never equal to a top-level folder of the repo.
   - data/slugs.js     window.CM_DATA.slugs (id -> slug) for the app: js/app.js routes #/<slug> and #/play/<slug|id>,
                       and the share button hands out <site>/play/<slug>/.
   - play/<slug>/index.html static share page (GitHub Pages: https://csardas223.github.io/ChessMaster/play/<slug>/)
                       with the mode's title, description and image as Open Graph / Twitter tags (what Discord,
                       WhatsApp, X, iMessage ... show), redirecting into the app at ../#/play/<id>. Folders of removed
                       modes are deleted (only folders carrying this script's marker are ever touched).
   - tools/share_ytimg.json  ids whose YouTube maxresdefault.jpg exists (refresh with --probe, needs network); the rest
                       use hqdefault.jpg. A mode card image (assets/modes/<id>/thumb.jpg) wins over YouTube.
   Usage: node tools/build-share.mjs [--base https://host/path/] [--probe] */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath, pathToFileURL } from 'node:url';

const SHARE_DIR = 'play'; /* all share pages live in <repo>/play/<slug>/ */
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const DEFAULT_BASE = 'https://csardas223.github.io/ChessMaster/';
const MARK = '<!-- generated by tools/build-share.mjs; do not edit by hand -->';
const RESERVED = new Set(['assets', 'css', 'data', 'docs', 'js', 'qa', 'research', 'tools', 'test', 'play', 'node_modules',
  'index', 'og', 'm', 'lobby', 'about', 'github', 'workflows']);

export function slugBase(s) {
  s = String(s || '').normalize('NFKD')
    .replace(/[\u0300-\u036f\u0483-\u0489\u1ab0-\u1aff\u1dc0-\u1dff\u20d0-\u20ff\ufe20-\ufe2f]/g, '').toLowerCase()
    .replace(/&/g, ' and ').replace(/\+/g, ' plus ').replace(/['\u2019`]/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  if (s.length > 48) { s = s.slice(0, 48); const k = s.lastIndexOf('-'); if (k > 20) s = s.slice(0, k); }
  return s;
}
const esc = (s) => String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const clean = (s) => String(s || '').normalize('NFKC').replace(/[\u0300-\u036f\u0483-\u0489\u1ab0-\u1aff\u1dc0-\u1dff\u20d0-\u20ff\ufe20-\ufe2f]/g, '').replace(/\s+/g, ' ').trim();
function short(s, n = 155) {
  s = clean(s); if (s.length <= n) return s;
  const cut = s.slice(0, n); const dot = cut.lastIndexOf('. ');
  return dot > 80 ? cut.slice(0, dot + 1) : cut.slice(0, cut.lastIndexOf(' ')).replace(/[,;:\s]+$/, '') + '\u2026';
}

/* modes: id -> {name, title, description, category, thumb, no_video}; videos: data/videos.json */
export function buildShare({ modes, videos, base = DEFAULT_BASE, log = console.log }) {
  base = base.endsWith('/') ? base : base + '/';
  const V = {}; for (const v of videos) V[v.id] = v;
  const regPath = path.join(ROOT, 'data', 'slugs.json');
  const prev = fs.existsSync(regPath) ? JSON.parse(fs.readFileSync(regPath, 'utf8')) : {};
  const topDirs = new Set(fs.readdirSync(ROOT, { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name)
    .filter(d => !fs.existsSync(path.join(ROOT, d, 'index.html')) || !fs.readFileSync(path.join(ROOT, d, 'index.html'), 'utf8').includes(MARK)));
  const bad = (s) => !s || RESERVED.has(s) || topDirs.has(s) || s.startsWith('.');
  const slugs = {}, used = new Set();
  for (const id of Object.keys(prev)) if (modes[id] && !bad(prev[id]) && !used.has(prev[id])) { slugs[id] = prev[id]; used.add(prev[id]); }
  const order = Object.keys(modes).filter(id => !slugs[id])
    .sort((a, b) => ((V[a] || {}).date || '9999').localeCompare((V[b] || {}).date || '9999') || a.localeCompare(b));
  for (const id of order) {
    const m = modes[id];
    const cands = [slugBase(m.name || m.title), slugBase((V[id] || {}).title || m.title)].map(c => (bad(c) ? (c ? c + '-mode' : '') : c));
    let s = cands.find(c => c && !used.has(c) && !bad(c));
    if (!s) { const b = cands[0] || slugBase(id) || 'mode'; let n = 2; while (used.has(b + '-' + n) || bad(b + '-' + n)) n++; s = b + '-' + n; }
    slugs[id] = s; used.add(s);
  }
  const sorted = Object.fromEntries(Object.keys(slugs).sort().map(k => [k, slugs[k]]));
  fs.writeFileSync(regPath, JSON.stringify(sorted, null, 1) + '\n');
  fs.writeFileSync(path.join(ROOT, 'data', 'slugs.js'), `/* generated by tools/build-share.mjs (registry data/slugs.json); do not edit by hand */\n` +
    `window.CM_DATA=window.CM_DATA||{};window.CM_DATA.slugs=${JSON.stringify(sorted)};\n`);

  const ytPath = path.join(ROOT, 'tools', 'share_ytimg.json');
  const maxres = new Set(fs.existsSync(ytPath) ? JSON.parse(fs.readFileSync(ytPath, 'utf8')).maxres || [] : []);
  let pages = 0;
  for (const id of Object.keys(sorted)) {
    const m = modes[id], v = V[id] || {}, slug = sorted[id];
    const name = clean(m.name || m.title || v.title || id);
    const title = name + ' \u00b7 Chess Master';
    const desc = short(m.description || v.teaser || v.summary || `Play ${name}, a chess variant from the iwantcheckmate videos, against the bot.`);
    const hasVideo = !m.no_video && !!V[id];
    const img = m.thumb ? base + m.thumb
      : hasVideo ? `https://i.ytimg.com/vi/${id}/${maxres.has(id) ? 'maxresdefault' : 'hqdefault'}.jpg` : base + 'assets/og/og-default.png';
    const url = base + SHARE_DIR + '/' + slug + '/', app = '../../#/play/' + encodeURIComponent(id);
    const html = `<!DOCTYPE html>
${MARK}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(desc)}">
<link rel="canonical" href="${esc(url)}">
<meta name="theme-color" content="#312e2b">
<link rel="icon" href="../../assets/img/logo.jpg">
<meta property="og:type" content="website">
<meta property="og:site_name" content="Chess Master">
<meta property="og:title" content="${esc(name)}">
<meta property="og:description" content="${esc(desc)}">
<meta property="og:url" content="${esc(url)}">
<meta property="og:image" content="${esc(img)}">
<meta property="og:image:alt" content="${esc(name)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(name)}">
<meta name="twitter:description" content="${esc(desc)}">
<meta name="twitter:image" content="${esc(img)}">
<meta http-equiv="refresh" content="0; url=${esc(app)}">
<script>location.replace(${JSON.stringify(app)});</script>
<style>body{background:#312e2b;color:#fff;font:16px/1.4 system-ui,sans-serif;display:grid;place-items:center;height:100vh;margin:0}a{color:#81b64c}</style>
</head>
<body><p>Opening <a href="${esc(app)}">${esc(name)}</a> in Chess Master&hellip;</p></body>
</html>
`;
    const dir = path.join(ROOT, SHARE_DIR, slug), f = path.join(dir, 'index.html');
    if (!fs.existsSync(f) || fs.readFileSync(f, 'utf8') !== html) { fs.mkdirSync(dir, { recursive: true }); fs.writeFileSync(f, html); }
    pages++;
  }
  /* drop share folders of modes that are gone or were re-slugged (in play/), and the old root-level share folders
     (before 2026-11-26 the pages sat at <repo>/<slug>/ and cluttered the repo root with ~500 folders) */
  const live = new Set(Object.values(sorted));
  let removed = 0;
  const sweep = (parent, keepLive) => {
    if (!fs.existsSync(parent)) return;
    for (const d of fs.readdirSync(parent, { withFileTypes: true })) {
      if (!d.isDirectory() || (keepLive && live.has(d.name))) continue;
      const f = path.join(parent, d.name, 'index.html');
      if (fs.existsSync(f) && fs.readFileSync(f, 'utf8').includes(MARK) && fs.readdirSync(path.join(parent, d.name)).length === 1) {
        fs.rmSync(path.join(parent, d.name), { recursive: true }); removed++;
      }
    }
  };
  sweep(path.join(ROOT, SHARE_DIR), true);
  sweep(ROOT, false);
  log(`share pages: ${pages} (${base}${SHARE_DIR}/<slug>/)` + (removed ? `, removed ${removed} stale` : ''));
  return sorted;
}

async function probe(ids) {
  const ok = [];
  for (let i = 0; i < ids.length; i += 24) {
    const batch = ids.slice(i, i + 24);
    const r = await Promise.all(batch.map(id => fetch(`https://i.ytimg.com/vi/${id}/maxresdefault.jpg`, { method: 'HEAD' }).then(x => x.ok, () => false)));
    batch.forEach((id, k) => r[k] && ok.push(id));
  }
  return ok.sort();
}

/* standalone: read the modes the same way build-data does */
export function readModes() {
  const dir = path.join(ROOT, 'data', 'modes'), out = {};
  for (const f of fs.readdirSync(dir).sort()) {
    if (!f.endsWith('.js') || f === 'index.js') continue;
    const got = [], sb = { window: {}, console: { log() { }, warn() { }, error() { } }, CM: { mode: (s) => { got.push(s); return s; }, defineHooks: () => { }, util: {} } };
    sb.window.CM = sb.CM;
    try { vm.runInNewContext(fs.readFileSync(path.join(dir, f), 'utf8'), sb, { timeout: 2000 }); } catch (e) { continue; }
    const s = got[0]; if (!s) continue;
    const id = f.replace(/\.js$/, '');
    const thumb = s.no_video && s.lobby && s.lobby.thumb ? s.lobby.thumb
      : fs.existsSync(path.join(ROOT, 'assets', 'modes', id, 'thumb.jpg')) ? `assets/modes/${id}/thumb.jpg` : null;
    out[id] = { name: s.name, title: s.title, description: s.description, category: s.category, thumb, no_video: !!s.no_video };
  }
  return out;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const a = process.argv, bi = a.indexOf('--base');
  const base = bi > 0 ? a[bi + 1] : DEFAULT_BASE;
  const videos = JSON.parse(fs.readFileSync(path.join(ROOT, 'data', 'videos.json'), 'utf8'));
  const modes = readModes();
  if (a.includes('--probe')) {
    const ids = Object.keys(modes).filter(id => !modes[id].no_video && videos.some(v => v.id === id));
    const maxres = await probe(ids);
    fs.writeFileSync(path.join(ROOT, 'tools', 'share_ytimg.json'), JSON.stringify({ note: 'ids whose i.ytimg.com maxresdefault.jpg exists; node tools/build-share.mjs --probe', maxres }, null, 0) + '\n');
    console.log(`maxres thumbnails: ${maxres.length}/${ids.length}`);
  }
  buildShare({ modes, videos, base });
}
