/* Mode specs: validation/normalisation, initial position building, and resolution of the mode a video plays.

   Resolution order for a video id (see ARCHITECTURE.md "How a video finds its mode"):
     1. data/modes/<id>.json     fetched over http(s)      (canonical, no build step needed)
     2. CM_DATA.modes[<id>]       from data/modes.bundle.js (generated by tools/build-data.mjs; used on file://)
     3. legacy                    the ported 8x8 mode library, configured by data/legacy_modes.js
   A spec may itself say { "engine": "legacy", "legacy": {mode, params, cfg} } to reuse a legacy mode while
   overriding presentation (opponent card, board colours, vfx_timeline, ...). */
(function () {
  'use strict';
  var CM = window.CM, U = CM.util;
  var KNOWN = ['id', 'title', 'name', 'category', 'description', 'how_to_win', 'player_side', 'opponent', 'player', 'board', 'pieces', 'setup',
    'rules', 'bot', 'clock', 'events', 'vfx', 'vfx_timeline', 'hooks', 'params', 'assets', 'sounds', 'engine', 'legacy', 'official_site_url',
    'source', 'notes', 'version', 'confidence', 'intro', 'messages', 'ui'];
  var STD_FEN = 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR';

  CM.hooks = CM.hooks || {};
  /* called by js/modes/<name>.js */
  CM.defineHooks = function (name, hooks) { CM.hooks[name] = hooks; return hooks; };

  function warn(spec, msg) { console.warn('[mode ' + (spec.id || '?') + '] ' + msg); }

  function normalize(spec) {
    var s = JSON.parse(JSON.stringify(spec || {}));
    Object.keys(s).forEach(function (k) { if (KNOWN.indexOf(k) < 0 && k[0] !== '_') warn(s, 'unknown top-level key "' + k + '" (ignored)'); });
    s.player_side = s.player_side === 'black' || s.player_side === 'b' ? 'b' : 'w';
    s.board = Object.assign({ files: 8, ranks: 8 }, s.board || {});
    s.setup = typeof s.setup === 'string' ? { fen: s.setup } : Object.assign({}, s.setup || {});
    if (!s.setup.fen && !s.setup.random) s.setup.fen = (s.board.files === 8 && s.board.ranks === 8) ? STD_FEN : new Array(s.board.ranks).fill(String(s.board.files)).join('/');
    s.opponent = Object.assign({ name: 'Stockfish', rating: 3600, avatar: null }, s.opponent || {});
    s.player = Object.assign({ name: 'You', rating: null, avatar: 'assets/avatars/you.svg' }, s.player || {});
    s.bot = Object.assign({ engine: 'auto' }, s.bot || {});
    if (s.bot.elo == null && typeof s.opponent.rating === 'number') s.bot.elo = s.opponent.rating;
    s.events = s.events || []; s.vfx = s.vfx || []; s.vfx_timeline = s.vfx_timeline || [];
    s.rules = s.rules || {};
    if (s.rules.win && !Array.isArray(s.rules.win)) s.rules.win = [s.rules.win];
    return s;
  }

  /* ------- FEN-like setup parser for any board size -------
     rows top (highest rank) first, separated by '/'. Uppercase = White, lowercase = Black.
     Digits (multi-digit allowed) = empty squares; holes count as squares too.
     '*' = wall, '[Id]' = White piece with a long id, '[id]' or '[b:Id]' = Black, '[n:Id]' = neutral.  */
  function parseSetup(V, fen) {
    var g = V.geo, b = new Array(g.size).fill(null), rows = String(fen).split(' ')[0].split('/');
    if (rows.length !== g.ranks) console.warn('[setup] FEN has ' + rows.length + ' rows for a board with ' + g.ranks + ' ranks');
    for (var r = 0; r < Math.min(rows.length, g.ranks); r++) {
      var row = rows[r], c = 0, k = 0;
      while (k < row.length && c < g.files) {
        var ch = row[k];
        if (/\d/.test(ch)) { var num = ''; while (k < row.length && /\d/.test(row[k])) num += row[k++]; c += +num; continue; }
        if (ch === '[') {
          var end = row.indexOf(']', k), tok = row.slice(k + 1, end); k = end + 1;
          var color = 'w', id = tok;
          if (/^[wbn]:/.test(tok)) { color = tok[0]; id = tok.slice(2); }
          else if (tok[0] === tok[0].toLowerCase() && tok[0] !== tok[0].toUpperCase()) { color = 'b'; id = findType(V, tok); }
          place(V, b, g.idx(c, r), id, color); c++; continue;
        }
        k++;
        if (ch === '*') { place(V, b, g.idx(c, r), '#', 'n'); c++; continue; }
        if (ch === '.') { c++; continue; }
        var up = ch.toUpperCase(), col = ch === up ? 'w' : 'b';
        place(V, b, g.idx(c, r), up, col); c++;
      }
    }
    return b;
  }
  function findType(V, lower) { var ids = Object.keys(V.types); for (var i = 0; i < ids.length; i++) if (ids[i].toLowerCase() === lower.toLowerCase()) return ids[i]; return lower; }
  function place(V, b, i, t, c) {
    if (!V.geo.valid[i]) { console.warn('[setup] piece on hole ' + V.geo.name(i) + ' ignored'); return; }
    if (!V.types[t]) console.warn('[setup] unknown piece type "' + t + '" (define it in spec.pieces)');
    b[i] = V.piece(t, c);
  }
  function chess960(V, b) {
    var a = new Array(8).fill(null), free = function (f) { var e = []; for (var i = 0; i < 8; i++) if (!a[i] && f(i)) e.push(i); return e[U.rand(e.length)]; };
    a[free(function (i) { return i % 2 === 0; })] = 'B'; a[free(function (i) { return i % 2 === 1; })] = 'B';
    a[free(function () { return true; })] = 'Q'; a[free(function () { return true; })] = 'N'; a[free(function () { return true; })] = 'N';
    var rest = []; for (var i = 0; i < 8; i++) if (!a[i]) rest.push(i); a[rest[0]] = 'R'; a[rest[1]] = 'K'; a[rest[2]] = 'R';
    for (var c = 0; c < 8; c++) { b[56 + c] = V.piece(a[c], 'w'); b[c] = V.piece(a[c], 'b'); b[48 + c] = V.piece('P', 'w'); b[8 + c] = V.piece('P', 'b'); }
  }

  function initialState(V, spec) {
    var su = spec.setup, g = V.geo, b;
    if (su.random === 'chess960') { b = new Array(g.size).fill(null); chess960(V, b); }
    else b = parseSetup(V, su.fen);
    (su.place || []).forEach(function (pl) {
      var squares = pl.at === 'random_empty' ? null : g.parseList(pl.at);
      var n = pl.count || (squares ? squares.length : 1);
      for (var k = 0; k < n; k++) {
        var sq = squares ? squares[k] : (function () { var e = []; for (var i = 0; i < g.size; i++) if (g.valid[i] && !b[i] && (!pl.rows || pl.rows.indexOf(g.rank(i)) >= 0)) e.push(i); return e.length ? e[U.rand(e.length)] : -1; })();
        if (sq >= 0) b[sq] = V.piece(pl.type, pl.color || 'w', pl.props || null);
      }
    });
    var st = { b: b, turn: su.turn === 'b' ? 'b' : 'w', ep: -1, epv: -1, ply: 0, half: 0, sub: 0,
      hands: { w: (su.hands && su.hands.w || []).slice(), b: (su.hands && su.hands.b || []).slice() }, checks: { w: 0, b: 0 }, x: Object.assign({}, su.x || {}) };
    /* pieces on their usual start squares count as unmoved; anything else counts as moved (no stray castling / double steps) */
    /* pawns off their second rank count as moved (no double step); setup.moved lists further squares to mark */
    b.forEach(function (p, i) { if (p && p.c !== 'n' && V.def(p.t).pawn && g.relRow(i, p.c) !== 1) b[i] = Object.assign({}, p, { m: 1 }); });
    g.parseList(su.moved).forEach(function (i) { if (b[i]) b[i] = Object.assign({}, b[i], { m: 1 }); });
    st.start = { wRoyal: V.royals(st, 'w').length > 0, bRoyal: V.royals(st, 'b').length > 0 };
    return st;
  }

  /* ------- loading ------- */
  var cache = {};
  function loadSpec(id) {
    if (cache[id]) return cache[id];
    var fromBundle = function () { var m = CM.DATA.modes && CM.DATA.modes[id]; return m ? JSON.parse(JSON.stringify(m)) : null; };
    var p;
    if (U.isFileProtocol) p = Promise.resolve(fromBundle());
    else p = U.fetchJSON('data/modes/' + encodeURIComponent(id) + '.json').catch(function () { return fromBundle(); });
    return (cache[id] = p.then(function (s) { if (!s) delete cache[id]; return s; }));
  }
  /* hooks: true -> js/modes/<id>.js ; "name" -> js/modes/<name>.js ; registered under CM.hooks[name] */
  function loadHooks(spec) {
    if (!spec.hooks) return Promise.resolve({});
    var name = spec.hooks === true ? spec.id : String(spec.hooks).replace(/^js\/modes\//, '').replace(/\.js$/, '');
    if (CM.hooks[name]) return Promise.resolve(CM.hooks[name]);
    return U.loadScript('js/modes/' + name + '.js').then(function () {
      if (!CM.hooks[name]) console.warn('[mode ' + spec.id + '] js/modes/' + name + '.js loaded but did not call CM.defineHooks("' + name + '", ...)');
      return CM.hooks[name] || {};
    }).catch(function (e) { console.error(e); return {}; });
  }
  function buildVariant(spec, hooks) {
    var cfg = { board: spec.board, pieces: spec.pieces, rules: spec.rules, hooks: hooks, params: spec.params || {} };
    return new CM.Variant(cfg);
  }

  CM.spec = { normalize: normalize, parseSetup: parseSetup, initialState: initialState, load: loadSpec, loadHooks: loadHooks, buildVariant: buildVariant, STD_FEN: STD_FEN };
})();
