#!/usr/bin/env node
/* Regenerates the classic-script data files the app loads synchronously (so it also runs from file://):
     data/videos.json        -> data/videos.js        (window.CM_DATA.videos)
     data/legacy_modes.json  -> data/legacy_modes.js  (window.CM_DATA.legacyModes)
     data/modes/*.json       -> data/modes.bundle.js  (window.CM_DATA.modes, keyed by video id)
   Over http(s) the app fetches data/modes/<id>.json directly, so a new spec works without rebuilding;
   rebuild before committing so file:// users and the lobby's "remastered" badges see it.
   Usage: node tools/build-data.mjs [--check]   (--check validates specs and exits non-zero on errors) */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = path.join(root, 'data');
const check = process.argv.includes('--check');
let errors = 0;

function wrap(name, obj) {
  return `/* generated by tools/build-data.mjs from data/${name}; do not edit by hand */\n` +
    `window.CM_DATA=window.CM_DATA||{};window.CM_DATA.${name.replace(/\.json$/, '').replace(/_(\w)/g, (_, c) => c.toUpperCase())}=${JSON.stringify(obj)};\n`;
}
const videos = JSON.parse(fs.readFileSync(path.join(data, 'videos.json'), 'utf8'));
const ids = new Set(videos.map(v => v.id));
fs.writeFileSync(path.join(data, 'videos.js'), wrap('videos.json', videos));
const legacy = JSON.parse(fs.readFileSync(path.join(data, 'legacy_modes.json'), 'utf8'));
fs.writeFileSync(path.join(data, 'legacy_modes.js'), wrap('legacy_modes.json', legacy));

const modes = {};
const dir = path.join(data, 'modes');
const REQUIRED = ['id'];
for (const f of fs.existsSync(dir) ? fs.readdirSync(dir).sort() : []) {
  if (!f.endsWith('.json')) continue;
  let spec;
  try { spec = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')); } catch (e) { console.error(`ERROR ${f}: invalid JSON: ${e.message}`); errors++; continue; }
  const id = f.replace(/\.json$/, '');
  for (const k of REQUIRED) if (spec[k] == null) { console.error(`ERROR ${f}: missing "${k}"`); errors++; }
  if (spec.id && spec.id !== id) { console.error(`ERROR ${f}: id "${spec.id}" does not match file name`); errors++; }
  if (!ids.has(id) && !id.startsWith('_')) console.warn(`warn  ${f}: no video with this id in data/videos.json (still bundled)`);
  if (spec.hooks) {
    const name = spec.hooks === true ? id : String(spec.hooks).replace(/^js\/modes\//, '').replace(/\.js$/, '');
    if (!fs.existsSync(path.join(root, 'js', 'modes', name + '.js'))) { console.error(`ERROR ${f}: hooks module js/modes/${name}.js not found`); errors++; }
  }
  if (id.startsWith('_')) continue;          /* _example.json etc. are documentation, not bundled */
  modes[id] = spec;
}
fs.writeFileSync(path.join(data, 'modes.bundle.js'), `/* generated by tools/build-data.mjs from data/modes/*.json; do not edit by hand */\nwindow.CM_DATA=window.CM_DATA||{};window.CM_DATA.modes=${JSON.stringify(modes)};\n`);
console.log(`videos: ${videos.length}, legacy configs: ${Object.keys(legacy).length}, mode specs bundled: ${Object.keys(modes).length}${errors ? `, ERRORS: ${errors}` : ''}`);
if (check && errors) process.exit(1);
